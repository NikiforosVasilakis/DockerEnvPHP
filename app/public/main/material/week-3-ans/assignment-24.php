<?php

// Define 'price' with a floating-point value.
$price = 49.65;

// Use 'round' to round the price to the nearest whole number.
echo "Rounded Price: " . round($price) . "<br>";

// Use 'ceil' to round the price up to the next whole number.
echo "Rounded Up Price: " . ceil($price) . "<br>";

// Use 'floor' to round the price down to the previous whole number.
echo "Rounded Down Price: " . floor($price);
